/// Phase: LLM test case -> IR generation -> trusted execution. Proves the *generator* (not just the
/// executor/validator, already generalized in `TestIRBranchExecutionTests`) produces the same IR schema for
/// natural-language test cases unrelated to DEMO-TC-872/Collection, and that malicious LLM output is rejected
/// at the correct stage of the pipeline (decode vs. semantic validation).
@Suite("IR.7 Generator Generalization")
struct TestIRGeneralizationTests {

    static func generate(_ ir: TestIR, stepsText: String) async throws -> TestIR {
        let mock = SequentialMockLLMClient(queuedResponses: [.success(String(data: ir.encoded(), encoding: .utf8)!)])
        return try await TestIRGenerator(llmClient: mock).generate(testKey: ir.testKey, title: ir.title, stepsText: stepsText)
    }

    static func target(_ role: String, id: String? = nil, label: String? = nil) -> IRTarget { IRTarget(role: role, identifier: id, label: label) }
    static func el(_ role: String, id: String? = nil, label: String? = nil) -> ScenarioExpectedElement { ScenarioExpectedElement(role: role, identifier: id, label: label) }

    // MARK: - Case A: "If the portfolio button exists, open Portfolio; otherwise open More." (branch)

    @Test("Case A: portfolio-exists-or-more generalizes through the same generator/validator/compiler, no DEMO-TC-872-specific logic")
    func testCaseAPortfolioOrMore() async throws {
        let sourceIR = TestIR(testKey: "GEN-A", title: "Portfolio or More", steps: [
            IRStep(id: "a-branch", sourceStepNumber: 1, intent: "open Portfolio if present, else More", action: .verifyOnly,
                   branch: IRBranch(
                       condition: .elementExists(Self.target("button", label: "Portfolio")),
                       thenSteps: [IRStep(id: "a-then", sourceStepNumber: 1, intent: "open Portfolio", action: .tap, target: Self.target("button", label: "Portfolio"),
                                          verification: IRVerification(description: "Portfolio opens", requiredElements: [Self.el("staticText", id: "portfolio_screen")]))],
                       elseSteps: [IRStep(id: "a-else", sourceStepNumber: 1, intent: "open More", action: .tap, target: Self.target("button", label: "More"),
                                          verification: IRVerification(description: "More opens", requiredElements: [Self.el("staticText", id: "more_screen")]))]))
        ])
        let ir = try await Self.generate(sourceIR, stepsText: "1. If the portfolio button exists, open Portfolio; otherwise open More.")
        let result = TestIRValidator.validate(ir)
        #expect(result.isAccepted)
        let branchStep = try #require(ir.steps.first { $0.branch != nil })
        guard case .elementExists = branchStep.branch!.condition else { Issue.record("expected elementExists"); return }

        // Execute both cases through the generic engine (same IRTestRunner used for DEMO-TC-872 and phase-2's
        // hand-built examples — nothing here is specific to this case).
        let frame = ElementFrame(x: 0, y: 0, width: 100, height: 40)
        do {
            let driver = SimulatedDriver(currentSnapshot: Observation(snapshotID: "s0", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
                elements: [UIElementSnapshot(id: "e1", role: "button", label: "Portfolio", frame: frame)]))
            await driver.queueNextSnapshot(Observation(snapshotID: "s1", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
                elements: [UIElementSnapshot(id: "e2", role: "staticText", identifier: "portfolio_screen", frame: frame)]))
            let (records, _) = try await IRTestRunner.run(ir.steps, verdicts: result.stepVerdicts, testKey: "GEN-A", title: ir.title,
                                                           credentials: [:], driver: driver, toolRegistry: ToolRegistry(projectRoot: URL(fileURLWithPath: "/tmp"), driver: driver))
            guard case .branchSelected(_, .then, _) = records[0] else { Issue.record("\(records)"); return }
        }
    }

    // MARK: - Case B: "Open Settings, select Notifications, and verify Notifications is displayed." (linear, no branch)

    @Test("Case B: Settings -> Notifications is a purely linear IR (no branch) generated by the same generator")
    func testCaseBSettingsNotifications() async throws {
        let sourceIR = TestIR(testKey: "GEN-B", title: "Settings Notifications", steps: [
            IRStep(id: "b1", sourceStepNumber: 1, intent: "open Settings", action: .tap, target: Self.target("button", label: "Settings"),
                   verification: IRVerification(description: "Settings opens", requiredElements: [Self.el("staticText", id: "settings_screen")])),
            IRStep(id: "b2", sourceStepNumber: 1, intent: "select Notifications", action: .tap, target: Self.target("button", label: "Notifications"),
                   verification: IRVerification(description: "Notifications selected", signals: [.selectedBecame(SignalLocator(role: "button", label: "Notifications"))])),
            IRStep(id: "b3", sourceStepNumber: 1, intent: "verify Notifications screen displayed", action: .verifyOnly,
                   verification: IRVerification(description: "Notifications screen visible", requiredElements: [Self.el("staticText", id: "notifications_screen")]))
        ])
        let ir = try await Self.generate(sourceIR, stepsText: "1. Open Settings, select Notifications, and verify that the Notifications screen is displayed.")
        let result = TestIRValidator.validate(ir)
        #expect(result.isAccepted)
        #expect(ir.steps.allSatisfy { $0.branch == nil }, "this case has no conditional logic at all")
        #expect(ir.steps.map(\.action) == [.tap, .tap, .verifyOnly])

        let frame = ElementFrame(x: 0, y: 0, width: 100, height: 40)
        let driver = SimulatedDriver(currentSnapshot: Observation(snapshotID: "s0", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
            elements: [UIElementSnapshot(id: "e1", role: "button", label: "Settings", isSelected: false, frame: frame)]))
        await driver.queueNextSnapshot(Observation(snapshotID: "s1", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
            elements: [UIElementSnapshot(id: "e2", role: "staticText", identifier: "settings_screen", frame: frame),
                       UIElementSnapshot(id: "e3", role: "button", label: "Notifications", isSelected: false, frame: frame)]))
        await driver.queueNextSnapshot(Observation(snapshotID: "s2", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
            elements: [UIElementSnapshot(id: "e3", role: "button", label: "Notifications", isSelected: true, frame: frame),
                       UIElementSnapshot(id: "e4", role: "staticText", identifier: "notifications_screen", frame: frame)]))
        let (records, _) = try await IRTestRunner.run(ir.steps, verdicts: result.stepVerdicts, testKey: "GEN-B", title: ir.title,
                                                       credentials: [:], driver: driver, toolRegistry: ToolRegistry(projectRoot: URL(fileURLWithPath: "/tmp"), driver: driver))
        #expect(records.count == 3)
        for record in records {
            guard case .step(_, let verified, let reason) = record else { Issue.record("\(records)"); continue }
            #expect(verified, Comment(rawValue: reason))
        }
    }

    // MARK: - Case C: "If the login form exists, fill it; otherwise navigate back and reopen Login." (branch, credential + navigateBack)

    @Test("Case C: login-form-exists-or-reopen generalizes with a credentialRef and navigateBack in the ELSE arm")
    func testCaseCLoginFormOrReopen() async throws {
        let sourceIR = TestIR(testKey: "GEN-C", title: "Login form or reopen", steps: [
            IRStep(id: "c-branch", sourceStepNumber: 1, intent: "fill the login form if present, else reopen it", action: .verifyOnly,
                   branch: IRBranch(
                       condition: .elementExists(Self.target("textField", id: "username_field")),
                       thenSteps: [
                           IRStep(id: "c-then-user", sourceStepNumber: 1, intent: "enter username", action: .typeText, target: Self.target("textField", id: "username_field"),
                                  arguments: ["text": .string("r.ruwan")], verification: IRVerification(description: "username entered", signals: [.valueChanged(identifier: "username_field")])),
                           IRStep(id: "c-then-pass", sourceStepNumber: 1, intent: "enter password", action: .typeText, target: Self.target("secureTextField", id: "password_field"),
                                  credentialRef: "TEST_USER_PASSWORD", verification: IRVerification(description: "password entered", signals: [.valueChanged(identifier: "password_field")]))
                       ],
                       elseSteps: [
                           IRStep(id: "c-else-back", sourceStepNumber: 1, intent: "navigate back", action: .navigateBack, target: Self.target("button", id: "nav_back_button")),
                           IRStep(id: "c-else-reopen", sourceStepNumber: 1, intent: "reopen Login", action: .tap, target: Self.target("button", label: "Login"),
                                  verification: IRVerification(description: "login form reopened", requiredElements: [Self.el("textField", id: "username_field")]))
                       ]))
        ])
        let ir = try await Self.generate(sourceIR, stepsText: "1. If the login form exists, fill it; otherwise navigate back and reopen Login.")
        let result = TestIRValidator.validate(ir)
        #expect(result.isAccepted)
        let branch = try #require(ir.steps.first { $0.branch != nil }?.branch)
        #expect(branch.thenSteps.contains { $0.credentialRef == "TEST_USER_PASSWORD" })
        #expect(branch.elseSteps.contains { $0.action == .navigateBack })
        // Never a plaintext password anywhere, even in this credentialed generalization case.
        let raw = String(data: ir.encoded(), encoding: .utf8) ?? ""
        #expect(!SecretRedactor.containsSecret(raw))

        // ELSE case: no username field present (form not shown) -> navigateBack + reopen, never typeText.
        let frame = ElementFrame(x: 0, y: 0, width: 100, height: 40)
        let driver = SimulatedDriver(currentSnapshot: Observation(snapshotID: "s0", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
            elements: [UIElementSnapshot(id: "e1", role: "button", identifier: "nav_back_button", frame: frame)]))
        await driver.queueNextSnapshot(Observation(snapshotID: "s1", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
            elements: [UIElementSnapshot(id: "e2", role: "button", label: "Login", frame: frame)]))
        await driver.queueNextSnapshot(Observation(snapshotID: "s2", bundleID: "com.apple.mobilesafari", appState: .runningForeground,
            elements: [UIElementSnapshot(id: "e3", role: "textField", identifier: "username_field", frame: frame)]))
        let (records, _) = try await IRTestRunner.run(ir.steps, verdicts: result.stepVerdicts, testKey: "GEN-C", title: ir.title,
                                                       credentials: ["TEST_USER_PASSWORD": "unused-in-this-arm"], driver: driver,
                                                       toolRegistry: ToolRegistry(projectRoot: URL(fileURLWithPath: "/tmp"), driver: driver))
        guard case .branchSelected(_, .else, _) = records[0] else { Issue.record("\(records)"); return }
        #expect((await driver.invokedActionCount["typeText"] ?? 0) == 0, "the THEN arm's credentialed typing must never run when the ELSE arm was selected")
        #expect((await driver.invokedActionCount["navigateBack"] ?? 0) == 1)
    }

    // MARK: - Malicious LLM output through the actual generator entry point (not a hand-crafted TestIR.decode call)

    @Test("An unknown-tool / shell-command LLM response fails to decode at TestIRGenerator.generate() itself (Fault A/B)")
    func testMaliciousDecodeLevelOutputRejectedByGenerator() async throws {
        for badAction in ["shell", "run_shell", "xcrun", "privateDriverMethod"] {
            let badJSON = #"{"schemaVersion": 1, "testKey": "BAD", "title": "t", "steps": [{"id":"s1","sourceStepNumber":1,"intent":"x","action":"\#(badAction)","arguments":{}}]}"#
            let mock = SequentialMockLLMClient(queuedResponses: [.success(badJSON)])
            await #expect(throws: TestIRGeneratorError.self) {
                _ = try await TestIRGenerator(llmClient: mock).generate(testKey: "BAD", title: "t", stepsText: "irrelevant")
            }
        }
    }

    @Test("A plaintext-password LLM response decodes (it is well-typed JSON) but TestIRValidator rejects it before execution (Fault C)")
    func testMaliciousSemanticLevelOutputDecodesButValidatorRejects() async throws {
        let step = IRStep(id: "s1", sourceStepNumber: 5, intent: "enter password", action: .typeText,
                           target: IRTarget(role: "secureTextField", identifier: "password_field"), arguments: ["text": .string("hunter2")])
        let sourceIR = TestIR(testKey: "BAD-2", title: "t", steps: [step])
        let mock = SequentialMockLLMClient(queuedResponses: [.success(String(data: sourceIR.encoded(), encoding: .utf8)!)])
        // generate() succeeds: the document is well-formed JSON matching the schema.
        let ir = try await TestIRGenerator(llmClient: mock).generate(testKey: "BAD-2", title: "t", stepsText: "irrelevant")
        #expect(ir.steps.first?.arguments["text"] == .string("hunter2"))
        // TestIRValidator is the stage that actually catches it, before anything compiles or executes.
        #expect(!TestIRValidator.validate(ir).isAccepted)
    }

    // MARK: - Faults D and F: structurally inexpressible in this IR schema (documented, not merely asserted)

    @Test("Fault D: the IR schema has no field to mark 'both arms executable' — selection is runtime-only, never data")
    func testBothArmsSimultaneouslyExecutableIsInexpressible() {
        // IRBranch's only fields are condition/thenSteps/elseSteps. There is no "selectedArm"/"executable"
        // flag anywhere for an LLM to set. A spoofed sibling field (as in Fault E) is inert dead data on
        // decode; there is no code path that reads "both arms" as a signal to run both — `nextSegment`
        // always recurses into exactly one arm (`arm == .then ? branch.thenSteps : branch.elseSteps`).
        let branch = IRBranch(condition: .elementExists(IRTarget(role: "button", label: "X")), thenSteps: [], elseSteps: [])
        let mirrorFields = Mirror(reflecting: branch).children.map { $0.label }
        #expect(mirrorFields == ["condition", "thenSteps", "elseSteps"])
    }

    @Test("Fault F: the IR schema carries no observation/snapshotID field — an LLM cannot reference or forge one")
    func testLLMCannotReferenceAnObservation() {
        // TestIR/IRStep/IRBranch/IRCondition carry no snapshotID, no Observation, no driver reference
        // anywhere. Freshness/staleness is enforced entirely at execution time by the existing trusted spine
        // (proven directly in TestIRBranchExecutionTests' stale-observation test) using `Observation` values
        // the driver produces — never a value that originates from generated IR.
        let mirrorFields = Mirror(reflecting: IRStep(id: "x", sourceStepNumber: 1, intent: "x", action: .verifyOnly)).children.map { $0.label }
        #expect(!mirrorFields.contains { $0?.lowercased().contains("snapshot") == true })
        #expect(!mirrorFields.contains { $0?.lowercased().contains("observation") == true })
    }
}
