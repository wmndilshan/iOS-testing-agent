import Foundation

/// Finds the repository's Swift sources, classifies them, and builds the `ASTIndex` (in parallel, reusing unchanged
/// files from an on-disk cache keyed by content hash). Build output, VCS data, run artifacts and generated code are
/// never read: every hidden directory (build output, VCS, run/skill/log stores, editor state) is skipped, plus the
/// non-hidden directories below.
public struct RepositoryScanner: Sendable {
    public static let excludedDirectories: Set<String> = [
        "DerivedData", "node_modules", "Pods", "Carthage", "xcuserdata", "generated", "Generated",
    ]

    static func isExcludedDirectory(_ name: String) -> Bool { name.hasPrefix(".") || excludedDirectories.contains(name) }
    static let excludedExtensions: Set<String> = ["xcresult", "xcarchive", "xcassets", "xcodeproj", "xcworkspace", "app", "dSYM"]

    public let root: URL

    public init(root: URL) { self.root = root.standardizedFileURL }

    /// Repository-relative paths of indexable Swift files, sorted.
    public func swiftFiles() -> [String] {
        files { $0.pathExtension == "swift" }.filter { !Self.isGenerated(path: $0, prefix: nil) }
    }

    /// Repository-relative paths of files named `name` (e.g. `SKILL.md`), sorted.
    public func files(named name: String) -> [String] { files { $0.lastPathComponent == name } }

    /// Repository-relative paths of Markdown documents (including `SKILL.md` files), sorted.
    public func markdownFiles() -> [String] { files { $0.pathExtension == "md" } }

    private func files(where include: (URL) -> Bool) -> [String] {
        guard let e = FileManager.default.enumerator(at: root, includingPropertiesForKeys: [.isDirectoryKey], options: [.skipsPackageDescendants]) else { return [] }
        var out: [String] = []
        for case let url as URL in e {
            let isDirectory = (try? url.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) ?? false
            if isDirectory {
                if Self.isExcludedDirectory(url.lastPathComponent) || Self.excludedExtensions.contains(url.pathExtension) { e.skipDescendants() }
                continue
            }
            if include(url) { out.append(relativePath(url)) }
        }
        return out.sorted()
    }

    func relativePath(_ url: URL) -> String {
        let path = url.standardizedFileURL.path
        return path.hasPrefix(root.path + "/") ? String(path.dropFirst(root.path.count + 1)) : path
    }

    /// Module (SwiftPM target or top-level folder) and role from the path alone.
    public static func classify(_ path: String) -> (module: String, role: FileRole) {
        let c = path.split(separator: "/").map(String.init)
        let ext = (path as NSString).pathExtension
        if ["md", "markdown", "txt", "rst"].contains(ext) { return (c.first ?? "", .documentation) }
        guard ext == "swift", c.count >= 2 else { return (c.first ?? "", .other) }
        switch c[0] {
        case "Sources": return (c[1], .production)
        case "Tests":
            let support = c.contains("Support") || c.contains("Fixtures") || c.last!.hasSuffix("TestSupport.swift") || c.last!.hasSuffix("Fixtures.swift")
            return (c[1], support ? .testSupport : .test)
        case "Package.swift": return ("Package", .other)
        default: return (c[0], .other)
        }
    }

    /// Generated sources are never indexed or sent to a model.
    static func isGenerated(path: String, prefix: String?) -> Bool {
        if path.hasSuffix(".generated.swift") || path.hasSuffix(".pb.swift") { return true }
        guard let prefix else { return false }
        let head = prefix.prefix(400).lowercased()
        return head.contains("// generated by") || head.contains("do not edit") || head.contains("@generated")
    }

    // MARK: Index

    public struct Statistics: Codable, Sendable {
        public var files = 0
        public var parsed = 0
        public var reusedFromCache = 0
        public var declarations = 0
        public var skippedGenerated = 0
        public var filesWithParseErrors = 0
    }

    /// Builds the index. `cacheURL`, if given, is read and rewritten; a missing or unreadable cache is not an error.
    /// `bodies: false` builds the declarations-only index (see `SwiftFileIndexer.index`); a cache written that way is never
    /// reused for a full index. `include` limits which repository-relative paths are indexed (for example to leave out tests).
    public func buildIndex(cacheURL: URL? = nil, bodies: Bool = true, include: (@Sendable (String) -> Bool)? = nil) -> (index: ASTIndex, statistics: Statistics) {
        let paths = include.map { filter in swiftFiles().filter(filter) } ?? swiftFiles()
        var loaded = cacheURL.flatMap(IndexCache.load) ?? IndexCache()
        if bodies, loaded.lightweight == true { loaded = IndexCache() }
        let cache = loaded
        let results = ResultBox(count: paths.count)
        DispatchQueue.concurrentPerform(iterations: paths.count) { i in
            let path = paths[i]
            guard let text = try? String(contentsOf: root.appendingPathComponent(path), encoding: .utf8) else { return }
            if Self.isGenerated(path: path, prefix: text) { results.set(i, .generated); return }
            let hash = Fingerprint.of(text)
            if let hit = cache.entries[path], hit.file.contentHash == hash { results.set(i, .indexed(hit, reused: true)); return }
            let (module, role) = Self.classify(path)
            let r = SwiftFileIndexer.index(path: path, module: module, role: role, source: text, bodies: bodies)
            results.set(i, .indexed(IndexCache.Entry(file: r.file, declarations: r.declarations), reused: false))
        }
        var index = ASTIndex()
        var stats = Statistics()
        var newCache = IndexCache()
        newCache.lightweight = bodies ? nil : true
        for (i, result) in results.values.enumerated() {
            switch result {
            case .indexed(let entry, let reused):
                index.add(file: entry.file, declarations: entry.declarations)
                newCache.entries[paths[i]] = entry
                stats.files += 1
                stats.declarations += entry.declarations.count
                if reused { stats.reusedFromCache += 1 } else { stats.parsed += 1 }
                if entry.file.parseErrorCount > 0 { stats.filesWithParseErrors += 1 }
            case .generated: stats.skippedGenerated += 1
            case nil: break
            }
        }
        // Rewriting an unchanged cache costs more than reading it: write only when a file was parsed or the set of files changed.
        if let cacheURL, stats.parsed > 0 || newCache.entries.count != cache.entries.count || newCache.lightweight != cache.lightweight { newCache.save(to: cacheURL) }
        return (index, stats)
    }
}

/// On-disk per-file index cache. Invalidated per file by content hash and globally by `version`.
struct IndexCache: Codable {
    struct Entry: Codable {
        var file: FileFacts
        var declarations: [Declaration]
    }
    /// Bump when the indexer's output format or semantics change.
    static let currentVersion = 3
    var version = IndexCache.currentVersion
    /// True when the entries were built without body facts. Optional so caches written before this field still load.
    var lightweight: Bool?
    var entries: [String: Entry] = [:]

    static func load(_ url: URL) -> IndexCache? {
        guard let data = try? Data(contentsOf: url), let cache = try? JSONDecoder().decode(IndexCache.self, from: data),
              cache.version == currentVersion else { return nil }
        return cache
    }

    func save(to url: URL) {
        try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try? JSONEncoder().encode(self).write(to: url, options: .atomic)
    }
}

private final class ResultBox: @unchecked Sendable {
    enum Result { case indexed(IndexCache.Entry, reused: Bool), generated }
    private let lock = NSLock()
    private(set) var values: [Result?]
    init(count: Int) { values = Array(repeating: nil, count: count) }
    func set(_ i: Int, _ r: Result) { lock.withLock { values[i] = r } }
}
